// Menghasilkan src/foundation/icons.generated.ts dari Phosphor Icons (MIT), bobot regular/bold/fill.
// Nama Ordinara -> nama file Phosphor. Jalankan: npm run gen:icons -w @ordinara/ui
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const assets = join(dirname(fileURLToPath(import.meta.url)), "../../../node_modules/@phosphor-icons/core/assets");
const out = join(dirname(fileURLToPath(import.meta.url)), "../src/foundation/icons.generated.ts");

const MAP = {
  house: "house", "layout-dashboard": "squares-four", "book-open": "book-open", users: "users", user: "user",
  bot: "robot", sparkles: "sparkle", settings: "gear", "circle-help": "question", shield: "shield",
  bell: "bell", search: "magnifying-glass", menu: "list", ellipsis: "dots-three",
  "panel-left-close": "sidebar-simple", "panel-left-open": "sidebar-simple", "log-out": "sign-out",
  sun: "sun", moon: "moon",
  "chevron-down": "caret-down", "chevron-up": "caret-up", "chevron-left": "caret-left", "chevron-right": "caret-right",
  "arrow-up": "arrow-up", "arrow-down": "arrow-down", "arrow-right": "arrow-right", "external-link": "arrow-square-out",
  x: "x", check: "check", plus: "plus", minus: "minus", pencil: "pencil-simple", "trash-2": "trash", copy: "copy",
  download: "download-simple", upload: "upload-simple", funnel: "funnel", eye: "eye", "eye-off": "eye-slash",
  info: "info", "circle-check": "check-circle", "circle-alert": "warning-circle", "triangle-alert": "warning",
  "circle-x": "x-circle", "loader-circle": "spinner", calendar: "calendar-blank", clock: "clock", star: "star",
  "chart-bar": "chart-bar", "chart-line": "chart-line-up", "qr-code": "qr-code", palette: "palette", type: "text-aa",
  shapes: "shapes", zap: "lightning", "swatch-book": "swatches", languages: "translate",
  "mouse-pointer-click": "cursor-click", package: "package", command: "command",
};
const WEIGHTS = { regular: "", bold: "-bold", fill: "-fill" };

const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s*\n\s*/g, "").trim();

const entries = Object.entries(MAP).map(([name, ph]) => {
  const w = Object.entries(WEIGHTS)
    .map(([weight, suffix]) => `${weight}: ${JSON.stringify(inner(readFileSync(join(assets, weight, `${ph}${suffix}.svg`), "utf8")))}`)
    .join(", ");
  return `  ${JSON.stringify(name)}: { ${w} },`;
});

writeFileSync(
  out,
  `// GENERATED by scripts/gen-icons.mjs dari Phosphor Icons (MIT). Jangan edit manual.\nexport const iconPaths = {\n${entries.join("\n")}\n} as const;\n\nexport type IconName = keyof typeof iconPaths;\nexport type IconWeight = "regular" | "bold" | "fill";\n`,
);
console.log(`wrote ${entries.length} icons -> ${out}`);
